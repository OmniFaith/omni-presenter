export async function loadNativeIcons(): Promise<void> {
  try {
    const response = await fetch("/api/control/icons");
    if (!response.ok) return;
    const remote = (await response.json()) as Record<string, string>;
    Object.assign(nativeGlyphs, remote);
    document
      .querySelectorAll<HTMLElement>(".native-icon[data-native-icon]")
      .forEach((element) => {
        const key = element.dataset.nativeIcon;
        const char = key ? nativeGlyphs[key] : undefined;
        if (char && element.textContent !== char) {
          element.textContent = char;
        }
      });
  } catch {
    /* Fallback remains usable while reconnecting. */
  }
}

export function icon(name: string): HTMLElement {
  const glyph = document.createElement("span");
  glyph.className = "native-icon";
  glyph.dataset.nativeIcon = name;
  glyph.textContent = nativeGlyphs[name] || name;
  glyph.setAttribute("aria-hidden", "true");
  return glyph;
}

export function paintIcons(): void {
  document
    .querySelectorAll<HTMLElement>("[data-icon]")
    .forEach((element) => {
      const name = element.dataset.icon;
      if (name) {
        element.replaceChildren(icon(name));
      }
    });
}

